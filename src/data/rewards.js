// 連擊獎勵：每 N 連擊的額外分數與一個道具。
//
// 為什麼要有這個：舊版連擊只是「殺得多分數高一點」——`addCombo()` 在 10 連擊時只彈一行
// 文字（`🔥 COMBO x10!`），沒有任何實質回饋，連擊窗口一旦斷掉（120 tick）也沒有損失感。
// 現在每 10 連擊給一次「額外分數 + 一個道具」，把「連續擊殺」變成值得主動維持的目標。
//
// 掉落池刻意排除 BOMB（一鍵清全場）：那會讓「連擊 → 更多連擊」變成滾雪球，
// 在高密度關卡裡直接洗分。這裡只給「強化自己」類的道具。

export const COMBO_REWARDS = {
  every: 10,            // 每 10 連擊一次里程碑
  scorePerTier: 100,    // 第 n 個里程碑給 n × 這個值
  maxTier: 5,           // 分數上限（第 5 個里程碑之後不再加乘，道具照給）
  pool: ['STAR', 'SHIELD', 'TIME', 'ONEUP', 'WALL'],
};
